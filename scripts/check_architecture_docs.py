#!/usr/bin/env python3
"""Check local documentation links, ADR identities and generated diagram views."""
import argparse
import os
from pathlib import Path
import re
import sys
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
MIRRORS = {
    "v2-System-Overview-Design.md": "00-product-baseline/System-Overview-Design.md",
    "v2-Technical-Architecture-Design.md": "00-product-baseline/Technical-Architecture-Design.md",
    "v2-Database-Overview-Design.md": "00-product-baseline/Database-Overview-Design.md",
    "v2-Implementation-Roadmap-and-Dependency-Graph.md": "00-product-baseline/Implementation-Roadmap-and-Dependency-Graph.md",
    "v2-Media-Delivery-CDN-Archive-Restore-Design.md": "02-domain-capabilities/Media-Delivery-CDN-Archive-Restore-Design.md",
}


def diagram_view(source, destination):
    text = source.read_text(encoding="utf-8")
    diagrams = re.findall(r"^```mermaid\s*\n(.*?)^```\s*$", text, re.M | re.S)
    link = os.path.relpath(source, destination.parent)
    result = f"# {text.splitlines()[0].lstrip('# ')}：图表\n\n"
    result += "<!-- Generated by scripts/check_architecture_docs.py --write-mirrors; do not edit. -->\n\n"
    result += f"来源：[{source.name}]({link})。规范正文以来源文档为准。\n"
    for index, diagram in enumerate(diagrams, 1):
        result += f"\n## 图 {index}\n\n```mermaid\n{diagram.rstrip()}\n```\n"
    if not diagrams:
        result += "\n本设计的流程与表格请查看来源文档。\n"
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write-mirrors", action="store_true")
    args = parser.parse_args()
    errors = []
    for name, canonical in MIRRORS.items():
        destination = DOCS / "90-diagrams" / name
        expected = diagram_view(DOCS / canonical, destination)
        if args.write_mirrors:
            destination.write_text(expected, encoding="utf-8")
        elif destination.read_text(encoding="utf-8") != expected:
            errors.append(f"stale diagram view: {destination.relative_to(ROOT)}")
    identities = {}
    for path in (DOCS / "00-product-baseline/adr").glob("ADR-*.md"):
        number = path.name.split("-", 2)[1]
        if number in identities:
            errors.append(f"duplicate ADR-{number}: {path.name}, {identities[number]}")
        identities[number] = path.name
    for path in DOCS.rglob("*.md"):
        fence = None
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = re.match(r"^\s*(`{3,}|~{3,})", line)
            if match:
                marker = match[1]
                if fence is None:
                    fence = marker
                elif marker[0] == fence[0] and len(marker) >= len(fence):
                    fence = None
                continue
            if fence:
                continue
            for target in re.findall(r"\]\(([^\s)]+)(?:\s+[^)]*)?\)", line):
                if re.match(r"^(?:[a-zA-Z][\w+.-]*:|#|/)", target):
                    continue
                file = unquote(target.split("#", 1)[0])
                if file and not (path.parent / file).exists():
                    errors.append(f"{path.relative_to(ROOT)}:{number}: missing {file}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print("Documentation links, ADR identities and generated diagrams: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
